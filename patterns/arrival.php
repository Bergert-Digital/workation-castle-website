<h3 class="wp-block-heading" id="bus">The bus from Lugano</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Bus C112 runs from Lugano to Menaggio — ticket about 6 €, around 30 minutes.</p>
