<h2 class="wp-block-heading">By plane</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Fly into <strong>Milano Malpensa (MXP)</strong>. A direct train runs from the airport to Lugano, roughly once an hour, and the quickest take about <strong>1h 35min</strong> — it's run by TILO/SBB and crosses the border without a change. From Lugano, take the bus up to Carlazzo (see below).</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Trains leave from <strong>Malpensa Aeroporto T1</strong>, right under the terminal. Check live times and fares on the <a href="https://www.sbb.ch/en/buying/pages/fahrplan/fahrplan.xhtml?von=Malpensa+Aeroporto&amp;nach=Lugano" target="_blank" rel="noreferrer noopener">SBB timetable</a> (Malpensa Aeroporto → Lugano).</p>
