#!/usr/bin/env node
/**
 * Block-catalog generator.
 *
 * Pure core (buildCatalog/extractWrapperClass/parsePreservedNotes) is unit
 * tested. The CLI gathers block.json from the Pediment plugin in the running
 * wp-env (read-only), the plugin's legacy block list (Policy::LEGACY) and the
 * client block.json from src/blocks, then writes docs/PEDIMENT-BLOCKS.md.
 *
 * Run: npm run blocks:catalog   (requires wp-env running)
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const NOTE_MARKER = '_(add guidance)_';

export function extractWrapperClass(renderPhp) {
  if (!renderPhp) return null;
  const m = renderPhp.match(/starter-[a-z0-9-]+/);
  return m ? m[0] : null;
}

export function parsePreservedNotes(existingDoc) {
  const notes = {};
  if (!existingDoc) return notes;
  const lines = existingDoc.split('\n');
  let current = null;
  for (const line of lines) {
    const h = line.match(/^## (\S+)/);
    if (h) { current = h[1]; continue; }
    const u = line.match(/^\*\*Use when:\*\*\s+(.*)$/);
    if (u && current) { notes[current] = u[1].trim(); current = null; }
  }
  return notes;
}

function attrLine(name, def) {
  const type = def && def.type ? def.type : 'unknown';
  return `  - \`${name}\` (${type})`;
}

const LEGACY_NOTE =
  'Do not use. Legacy block: hidden from the inserter, deleted in Pediment 5. ' +
  'Compose it from core blocks and named styles (see `docs/STYLING.md`, ' +
  '"Compose sections from core blocks").';

export function buildCatalog(records, existingDoc, legacy = []) {
  const notes = parsePreservedNotes(existingDoc);
  const legacyNames = new Set(legacy);
  const sorted = [...records].sort((a, b) =>
    a.blockJson.name.localeCompare(b.blockJson.name));
  const current = sorted.filter((r) => !legacyNames.has(r.blockJson.name));
  const retired = sorted.filter((r) => legacyNames.has(r.blockJson.name));

  const out = [];
  out.push('# Pediment block catalog');
  out.push('');
  out.push('> Generated by `npm run blocks:catalog`. Edit only the **Use when** notes —');
  out.push('> everything else is overwritten on regeneration. Do not hand-edit other fields.');
  out.push('>');
  out.push('> Pages are composed from core blocks and named block styles. Only the blocks');
  out.push('> in this first part are for new content. The blocks under "Legacy blocks" are');
  out.push('> kept so old content renders; never insert them.');
  out.push('');

  for (const { source, blockJson, renderPhp } of current) {
    const cls = extractWrapperClass(renderPhp);
    const note = notes[blockJson.name] || NOTE_MARKER;
    out.push(`## ${blockJson.name}`);
    out.push('');
    out.push(`**${blockJson.title || ''}** — ${blockJson.description || ''}`.trim());
    out.push('');
    out.push(`**Source:** ${source}`);
    if (cls) out.push(`**Wrapper class:** \`${cls}\``);
    out.push(`**Use when:** ${note}`);
    out.push('');
    const attrs = blockJson.attributes || {};
    if (Object.keys(attrs).length) {
      out.push('**Attributes:**');
      for (const [name, def] of Object.entries(attrs)) out.push(attrLine(name, def));
      out.push('');
    }
    const align = blockJson.supports && blockJson.supports.align;
    if (align) { out.push(`**Align:** ${align.join(', ')}`); out.push(''); }
  }

  if (retired.length) {
    out.push('# Legacy blocks (do not use)');
    out.push('');
    out.push('> `Policy::LEGACY` in the Pediment plugin. Hidden from the inserter, deleted in');
    out.push('> Pediment 5. Convert existing uses with `wp pediment convert`.');
    out.push('');
    for (const { source, blockJson } of retired) {
      out.push(`## ${blockJson.name}`);
      out.push('');
      out.push(`**${blockJson.title || ''}** — ${blockJson.description || ''}`.trim());
      out.push('');
      out.push(`**Source:** ${source}`);
      out.push('**Status:** legacy');
      out.push(`**Use when:** ${LEGACY_NOTE}`);
      out.push('');
    }
  }
  return out.join('\n');
}

// Pediment ships as a plugin. Publish mode installs the release zip as
// `pediment-plugin`; dev mode (`npm run env:dev`) mounts the sibling working
// copy, which wp-env names after its directory basename, `plugin`. Probe both:
// an unmatched glob stays literal in sh and its `cat` just prints nothing.
const PLUGIN_ROOTS = [
  'wp-content/plugins/pediment-plugin',
  'wp-content/plugins/plugin',
];
const PARENT_DIRS = PLUGIN_ROOTS.map((r) => `${r}/build/blocks`);
const DELIM_FILE = '@@@FILE:';
const DELIM_RENDER = '@@@RENDER:';

export function parentBlocksScript() {
  return (
    `for d in ${PARENT_DIRS.map((p) => `${p}/*/`).join(' ')}; do ` +
    `echo "${DELIM_FILE}$d"; cat "$d/block.json" 2>/dev/null; ` +
    `echo; echo "${DELIM_RENDER}$d"; cat "$d/render.php" 2>/dev/null; echo; done`
  );
}

export function parseParentBlocks(raw) {
  const records = [];
  // Split on the FILE delimiter; ignore wp-env banner text before the first one.
  const chunks = raw.split(DELIM_FILE).slice(1);
  for (const chunk of chunks) {
    const [, jsonAndRest = ''] = chunk.match(/^.*?\n([\s\S]*)$/) || [];
    const [jsonPart = '', renderPart = ''] = jsonAndRest.split(DELIM_RENDER);
    const renderPhp = renderPart.replace(/^.*?\n/, '');
    try {
      const blockJson = JSON.parse(jsonPart.trim());
      records.push({ source: 'parent', blockJson, renderPhp });
    } catch { /* skip non-JSON noise */ }
  }
  return records;
}

// The plugin lists its legacy blocks in Policy::LEGACY. Read the list from the
// installed plugin so the catalog follows the Pediment release in wp-env.
export function parseLegacyBlocks(policyPhp) {
  const m = policyPhp.match(/const\s+LEGACY\s*=\s*array\(([\s\S]*?)\)\s*;/);
  if (!m) return [];
  return [...m[1].matchAll(/'([a-z0-9-]+\/[a-z0-9-]+)'/g)].map((x) => x[1]);
}

export function legacyScript() {
  // Only one root exists per wp-env mode; the missing one fails its cat, so end on `true`.
  return PLUGIN_ROOTS.map((r) => `cat ${r}/src/Content/Policy.php 2>/dev/null`).join('; ') + '; true';
}

function gatherLegacyBlocks() {
  let raw;
  try {
    raw = execFileSync('npx', ['wp-env', 'run', 'cli', 'sh', '-c', legacyScript()],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    throw new Error('Could not read the plugin legacy block list from wp-env.\n' +
      (e.stderr || e.message));
  }
  const legacy = parseLegacyBlocks(raw);
  if (!legacy.length) {
    throw new Error('No Policy::LEGACY list found in the Pediment plugin. Aborting so ' +
      'legacy blocks are not listed as current.');
  }
  return legacy;
}

// Read parent block.json + render.php out of the running wp-env (read-only).
function gatherParentRecords() {
  let raw;
  try {
    raw = execFileSync('npx', ['wp-env', 'run', 'cli', 'sh', '-c', parentBlocksScript()],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    throw new Error('Could not read parent blocks from wp-env. Is it running? ' +
      'Run `npm run env:start` first.\n' + (e.stderr || e.message));
  }
  const records = parseParentBlocks(raw);
  // The plugin always ships blocks; zero means the path probe found nothing.
  // Abort instead of writing a catalog with every pediment/* entry dropped.
  if (!records.length) {
    throw new Error(
      `No parent blocks found under ${PARENT_DIRS.join(' or ')} — ` +
      'is the Pediment plugin installed in wp-env? Aborting so the ' +
      "catalog's pediment/* entries are not clobbered.");
  }
  return records;
}

async function gatherChildRecords(repoRoot) {
  const base = join(repoRoot, 'src', 'blocks');
  const records = [];
  let dirs = [];
  try { dirs = await readdir(base, { withFileTypes: true }); } catch { return records; }
  for (const d of dirs) {
    if (!d.isDirectory()) continue;
    try {
      const blockJson = JSON.parse(await readFile(join(base, d.name, 'block.json'), 'utf8'));
      let renderPhp = '';
      try { renderPhp = await readFile(join(base, d.name, 'render.php'), 'utf8'); } catch {}
      records.push({ source: 'child', blockJson, renderPhp });
    } catch { /* dir without a valid block.json */ }
  }
  return records;
}

async function main() {
  const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
  const docPath = join(repoRoot, 'docs', 'PEDIMENT-BLOCKS.md');
  let existing = '';
  try { existing = await readFile(docPath, 'utf8'); } catch {}
  const records = [...gatherParentRecords(), ...await gatherChildRecords(repoRoot)];
  if (!records.length) throw new Error('No blocks found — aborting (would clobber the catalog).');
  const legacy = gatherLegacyBlocks();
  await writeFile(docPath, buildCatalog(records, existing, legacy) + '\n', 'utf8');
  console.log(`Wrote ${records.length} blocks to docs/PEDIMENT-BLOCKS.md`);
}

if (import.meta.main) {
  main().catch((e) => { console.error(e.message); process.exit(1); });
}
